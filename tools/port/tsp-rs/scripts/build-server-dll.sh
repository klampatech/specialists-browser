#!/usr/bin/env bash
# Build the TS port's SERVER DLL for Linux (the artefact the game server
# image installs as ts_amd64_amd64.so).
#
# WHY THIS SCRIPT EXISTS
#
# `cargo xtask build --release` builds every target, including the
# Windows i686 one, which needs a Rust target this box does not have —
# so it fails before it ever starts on the server DLL. And a bare
# `cargo build -p ts-server-dll` fails three ways that the errors do not
# explain:
#
#   1. "FWGS headers not found: set FWGS_DIR to an xash3d-fwgs checkout"
#      — the crate binds the engine's C headers, so it needs a FULL
#        xash3d-fwgs checkout (with common/, engine/, public/, and the
#        generated public/build.h), not a partial one.
#   2. "Unable to find libclang" — bindgen needs libclang.
#   3. "stddef.h file not found" — clang's own resource headers are
#      not where the unpacked libclang expects them; the GCC headers
#      have to be added to the include path.
#
# This script finds all three and reports exactly what it used.
#
#   usage: scripts/build-server-dll.sh [--release]
#   output: target/x86_64-unknown-linux-gnu/release/libts.so
#
# The result is installed by copying it over the game's
# ts/dlls/ts_amd64_amd64.so.
set -euo pipefail

RELEASE=1
for arg in "$@"; do
  case "$arg" in
    --release) RELEASE=1 ;;
    --debug) RELEASE=0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
port="$(cd "$here/.." && pwd)"

say() { printf '[build-server-dll] %s\n' "$*"; }
die() { printf '[build-server-dll] ERROR: %s\n' "$*" >&2; exit 1; }

# --- 1. the xash3d-fwgs checkout -------------------------------------------------
# It has to be a full checkout: the build script's include paths are
# common/, engine/, pm_shared/, public/ and 3rdparty/library_suffix/include,
# and public/build.h is generated by the engine's own build.
find_fwgs() {
  local c
  if [[ -n "${FWGS_DIR:-}" && -f "$FWGS_DIR/public/build.h" ]]; then
    printf '%s' "$FWGS_DIR"; return
  fi
  for c in \
    "$port/xash3d-fwgs" \
    "$port/../xash3d-fwgs" \
    "$HOME/Development/xash3d-fwgs" \
    "$HOME/Development/xash3d-fwgs-fwgs" \
    /tmp/xash3d-fwgs \
    /tmp/serve/xash3d-fwgs \
    /opt/xash3d-fwgs; do
    [[ -f "$c/public/build.h" ]] && { printf '%s' "$c"; return; }
  done
}
fwgs="$(find_fwgs || true)"
[[ -n "$fwgs" ]] || die "no xash3d-fwgs checkout found. Set FWGS_DIR to one that has public/build.h (a full checkout, not a partial one)."
export FWGS_DIR="$fwgs"
say "FWGS_DIR=$FWGS_DIR"

# --- 2. libclang ------------------------------------------------------------------
find_libclang() {
  local c
  if [[ -n "${LIBCLANG_PATH:-}" ]] && ls "$LIBCLANG_PATH"/libclang*.so* >/dev/null 2>&1; then
    printf '%s' "$LIBCLANG_PATH"; return
  fi
  for c in \
    /usr/lib/llvm-*/lib \
    /usr/lib/x86_64-linux-gnu \
    /usr/lib64 \
    /tmp/libclang-dl/extracted2/usr/lib/x86_64-linux-gnu \
    /tmp/libclang-dl/extracted/usr/lib/x86_64-linux-gnu; do
    ls "$c"/libclang.so* >/dev/null 2>&1 && { printf '%s' "$c"; return; }
  done
}
libclang="$(find_libclang || true)"
if [[ -z "$libclang" ]]; then
  say "no libclang found — trying the system package"
  if sudo -n apt-get install -y libclang-dev >/dev/null 2>&1; then
    libclang="$(find_libclang || true)"
  fi
fi
[[ -n "$libclang" ]] || die "libclang not found. Install it (apt-get install libclang-dev) or point LIBCLANG_PATH at a directory holding libclang.so*."
export LIBCLANG_PATH="$libclang"
say "LIBCLANG_PATH=$LIBCLANG_PATH"

# --- 3. the C headers clang cannot find on its own ---------------------------------
# clang's resource headers live in its own resource directory, which an
# unpacked libclang does not always carry; GCC's do, and they are
# compatible for this purpose.
gcc_include="$(ls -d /usr/lib/gcc/*/*/include 2>/dev/null | sort -V | tail -1 || true)"
if [[ -n "$gcc_include" ]]; then
  export BINDGEN_EXTRA_CLANG_ARGS="-I$gcc_include -I/usr/include/$(uname -m)-linux-gnu"
  say "BINDGEN_EXTRA_CLANG_ARGS=$BINDGEN_EXTRA_CLANG_ARGS"
else
  say "no GCC include directory found; relying on the system headers"
fi

# --- build ------------------------------------------------------------------------
profile=(--release)
[[ "$RELEASE" = 1 ]] || profile=()
cd "$port"
say "building ts-server-dll (${profile[*]:-debug})"
cargo build "${profile[@]}" -p ts-server-dll --target x86_64-unknown-linux-gnu

out="$port/target/x86_64-unknown-linux-gnu/release/libts.so"
[[ -f "$out" ]] || out="$port/target/x86_64-unknown-linux-gnu/debug/libts.so"
[[ -f "$out" ]] || die "the build finished but libts.so is not where it should be"
say "built: $out"
say "install it as the game's ts/dlls/ts_amd64_amd64.so"
