/**
 * CTSGun::TakeWeapon — equip an instance of `weapon_id` for the
 * player. Picks an inventory slot for this weapon type, copies
 * state from `src_status` (or initialises from weapon-db defaults),
 * and updates the player's "owns this weapon" bitmask.
 *
 * Special handling is applied for akimbo (dual-wield) weapons
 * (which merge primary + sidearm ammo) and "only-akimbo" weapons
 * (which split their default ammo evenly between two magazines).
 *
 * @param this        The CTSGun entity managing this player's weapons.
 * @param weapon_id   Weapon type id. Must satisfy 0 <= id <= 0x25.
 * @param src_status  Pointer to a source s_weapon_status struct to
 *                    copy 0x38 bytes from. May be 0 to skip the
 *                    copy and initialise from defaults instead.
 * @param flags       Bit flags to OR into the new slot's bitmask word.
 * @returns           1 on success; 0 if weapon_id is out of range or
 *                    the weapon type is not registered in the db.
 *
 * Helpers used below that are introduced by this decompilation pass
 * (and so do not exist yet on the CTSGun class) are marked with
 * helper-name TODO comments. Real PLT calls (IsWeaponAkimbo /
 * IsOnlyAkimbo) match symbols in the .so directly.
 */
export function TakeWeapon(
  this: CTSGun,
  weapon_id: number,
  src_status: number,
  flags: number
): number {
  // ===== 1. Range check on weapon_id =================================
  // asm 0x70a17..0x70a23:  cmp ecx, 0x25 ; ja fail
  if (weapon_id > 0x25) return 0;

  // ===== 2. Verify the weapon type is registered in the global db =====
  // The weapon-db lives at PIC-base + 0x7d30 with 988-byte entries;
  // the first byte of an entry is the "valid" flag.
  //
  // TODO(asm-ambiguous): the *988 per-id index is generated by
  //   shl 5; sub eax, ecx; shl 3; sub eax, ecx; *4
  // which is ((id*247) << 2) == id * 988. That implies
  // sizeof(s_weapon_db_entry) == 0x3dc (988). The shl/sub sequence
  // is an MSVC codegen quirk — verify the actual struct size matches.
  const weaponDbBase = (this as any).__picBase + 0x7d30;
  if (loadU8(weaponDbBase + weapon_id * 988) === 0) return 0;

  // ===== 3. Resolve which inventory slot to populate =================
  // Two candidate slot locations per the chunk asm 0x70a17..0x70b9b:
  //   - Primary: per-weapon status array, stride 56 bytes per id,
  //     the slot's first field (active flag) sits at offset +0x114
  //     from the start of the array. asm 0x70a44..0x70b9b.
  //   - Secondary: a redirect table inside the db entry at offsets
  //     0xc0 / 0xc8 / 0xdc / 0xe0, which can swap in a different
  //     `targetWeaponId`. asm 0x70aa4..0x70b2a.
  //
  // When the resolved slot is already active AND the per-stack cap is
  // not exceeded, the function just bumps the stack count and returns
  // success (asm 0x70bcf..0x70be7). Otherwise fall through and fill
  // the slot from `src_status` (or from db defaults).
  //
  // TODO(asm-ambiguous): the slot-resolution logic spans ~10 branches
  // and reads from both the status array and the db entry
  // simultaneously. We expose it as a method helper for readability.
  // const slot = this.__resolveTakeSlot(weapon_id);
  const slot = this.__resolveTakeSlot(weapon_id); // TODO: helper from §3 above
  if (slot.wasAlreadyActive) {
    // Duplicate pickup — bump the stack count and return 1.
    slot.stackCount += 1;
    return 1;
  }

  // ===== 4. Populate the slot ========================================
  // The slot is an `s_weapon_status` struct (~0x38 bytes). Field
  // layout below is inferred from the asm reads/writes; details at
  // offsets +0x01 and +0x24 are educated guesses.
  //
  //   +0x00: active flag (byte)
  //   +0x01: display byte (loaded from db +0x08)
  //   +0x02: mode byte (derived from db flag bits; see §4b)
  //   +0x04: primary ammo (dword)
  //   +0x08: secondary ammo (dword)
  //   +0x0c: bitmask (dword)
  //   +0x10: bitmask2 (dword)
  //   +0x14: sub-bitmask (dword)
  //   +0x18: tick counter (dword)
  //   +0x1c..0x20: ammo splits (used by akimbo path)
  //   +0x24: 'has weapon' flag byte
  //   +0x28: next-free cache head pointer (dword)
  //   +0x114: alternate base for the same fields (see §3)
  if (src_status !== 0) {
    // Path A — bulk-copy 0x38 bytes from src_status via rep movsd
    // (ecx = 0xe = 14 dwords), then zero clip/secondary ammo and
    // set active=1. asm 0x70bf7..0x70c15.
    slot.copyFrom(src_status, 0x38);
    slot.active        = 1;
    slot.ammoClip      = 0;
    slot.ammoSecondary = 0;
  } else {
    // Path B — initialise just active + display, leave ammo for the
    // akimbo/normal branches below. asm 0x70d4c..0x70d59.
    slot.active        = 1;
    slot.modeDisplay   = loadU8(weaponDbBase + weapon_id * 988 + 0x08);
    slot.ammoSecondary = 0;
  }

  // ===== 4b. Slot mode byte ==========================================
  // Derived from db flag bits 0x1, 0x8, 0x4 with an MSVC test/set
  // pattern producing:
  //   if (db.flags & 0x1) → mode = 0
  //   else if (db.flags & 0x8) → mode = 3
  //   else                      → mode = (db.flags & 0x4) ? 1 : 2
  //
  // asm 0x70cfd..0x70d34 (path A) / 0x70d60..0x70d98 (path B).
  {
    const dbFlags = loadU32(weaponDbBase + weapon_id * 988 + 0x0c);
    if      (dbFlags & 0x1) slot.mode = 0;
    else if (dbFlags & 0x8) slot.mode = 3;
    else                    slot.mode = (dbFlags & 0x4) ? 1 : 2;
  }

  // ===== 5. Ammo + akimbo handling ===================================
  if (IsWeaponAkimbo(weapon_id)) {
    // Akimbo (dual-wield) weapons: pull sidearm id from
    // weapon_db +0xcc, then read its primary ammo from the per-weapon
    // status array and combine with the slot primary ammo. Update
    // both the slot bitmask and the sidearm's mirror-field at
    // weapon_db +0x120.
    //
    // asm 0x70c25..0x70cfe  (path A)
    //      0x70da4..0x70e79  (path B)
    //
    // The two paths differ in which slot offsets they touch
    // (path A uses slot[0x4]/[0x1c]/[0x20] directly because the bulk
    // copy in step 4 wiped them and left them ready to receive;
    // path B sets slot[0x1c]/[0x20] first and slot[0x4] = sum).
    //
    // TODO(asm-ambiguous): the akimbo-merge is branch-heavy and
    // interleaves reads/writes between the slot and the db entry —
    // it would expand to ~25 lines of TS, all of which is byte
    // arithmetic against offsets rather than algorithmic logic.
    // Inlining here would obscure rather than clarify.
    mergeAkimboAmmo(slot, weaponDbBase, weapon_id, flags); // TODO helper
  } else if (IsOnlyAkimbo(weapon_id)) {
    // Only-akimbo weapons split their default ammo evenly between
    // the two magazines (sar 1 with round-up bias). asm 0x70e8d..0x70ecd.
    const fullAmmo = loadU32(weaponDbBase + weapon_id * 988 + 0x04);
    const halfAmmo = fullAmmo >>> 1;
    slot.ammoPrimary   = halfAmmo;
    slot.ammoSecondary = halfAmmo;
    slot.ammoTotal     = fullAmmo;
    slot.bitmask       = flags | loadU32(weaponDbBase + weapon_id * 988 + 0xe4);
    slot.bitmask2      = 0;
  } else {
    // Standard single-handed pickup. asm 0x70ed0..0x70ee7.
    slot.ammoTotal = loadU32(weaponDbBase + weapon_id * 988 + 0x04);
    slot.bitmask   = flags | loadU32(weaponDbBase + weapon_id * 988 + 0xe4);
    slot.bitmask2  = 0;
  }

  // ===== 6. Final bookkeeping ========================================
  // Zero per-tick counters and link this slot into the per-weapon
  // "next-free" cache list head (head pointer lives at
  // weaponDbBase + weapon_id*988 + 0x252). asm 0x70eee..0x70f0a.
  slot.tickCounter = 0;
  slot.unkByte     = 0;
  slot.ammoClip    = 0;
  slot.nextFree    = weaponDbBase + weapon_id * 988 + 0x252;

  // Apply the db's per-weapon "owned-weapons" mask to bitmask.
  // asm 0x70f0d..0x70f16.
  slot.bitmask &= loadU32(weaponDbBase + weapon_id * 988 + 0xe0);

  // Propagate the persist-on-pickup bits 0x2 and 0x4 into bitmask2.
  // asm 0x70f19..0x70f2e.
  if (slot.bitmask & 0x2) slot.bitmask2 |= 0x2;
  if (slot.bitmask & 0x4) slot.bitmask2 |= 0x4;

  return 1;
}
